import requests

from flask import redirect, render_template, session
from functools import wraps


def apology(message, code=400):
    """Render message as an apology to user."""

    def escape(s):
        """
        Escape special characters.

        https://github.com/jacebrowning/memegen#special-characters
        """
        for old, new in [
            ("-", "--"),
            (" ", "-"),
            ("_", "__"),
            ("?", "~q"),
            ("%", "~p"),
            ("#", "~h"),
            ("/", "~s"),
            ('"', "''"),
        ]:
            s = s.replace(old, new)
        return s

    return render_template("apology.html", top=code, bottom=escape(message)), code


def login_required(f):
    """
    Decorate routes to require login.

    https://flask.palletsprojects.com/en/latest/patterns/viewdecorators/
    """

    @wraps(f)
    def decorated_function(*args, **kwargs):
        if session.get("user_id") is None:
            return redirect("/login")
        return f(*args, **kwargs)

    return decorated_function


def lookup(symbol):
    """Look up quote for symbol."""
    url = f"https://finance.cs50.io/quote?symbol={symbol.upper()}"
    try:
        response = requests.get(url)
        response.raise_for_status()  # Raise an error for HTTP error responses
        quote_data = response.json()
        return {
            "name": quote_data["companyName"],
            "price": quote_data["latestPrice"],
            "symbol": symbol.upper()
        }
    except requests.RequestException as e:
        print(f"Request error: {e}")
    except (KeyError, ValueError) as e:
        print(f"Data parsing error: {e}")
    return None


def usd(value):
    """Format value as USD."""
    return f"${value:,.2f}"

def join_stocks(symbol,stocks):
    n_shares = 0
    for stock in stocks:
        if stock["stock"] == symbol:
            n_shares += int(stock["shares"])
    return n_shares

def make_stock_list(stock_list,name_list,stocks):
    for stock in stocks:
        stock_dict = {}
        temp = lookup(stock["stock"])
        if temp["name"] in name_list:
            continue

        name_list.append(temp["name"])
        stock_dict["name"] = temp["name"]
        stock_dict["shares"] = join_stocks(stock["stock"],stocks)
        stock_dict["price"] = temp["price"]
        stock_dict["total_value"] = float(stock_dict["price"]) * float(stock_dict["shares"])
        stock_list.append(stock_dict)
